#!/usr/bin/env python3
"""Generate bootenv.cpp from a DOSBox-X memory capture taken at the program's (unpacked) entry point.

    python3 make_bootenv.py mem_entry.bin OUT/bootenv.cpp --psp 0x0814 --first-mcb 0x0450 \
        --regs "ax=0 bx=0 cx=0 dx=F000 si=2A3F di=0800 bp=0 sp=0800 ds=0814 es=0814 ss=2A3F cs=21E5 ip=0944 flags=3206" \
        --vga-log VGA.TXT --break-log BREAK.TXT

Captured as data: the reference machine's memory outside the program (refmachine.regions: IVT, BDA,
DOS data, MCB chain, environment, PSP, video/system ROM, HMA), the callback-to-vector map of its BIOS/DOS
stubs, the entry registers, the BIOS timer tick phase and the display timing (refmachine.vga_timing, from the REA_LOG_VGA and
REA_LOG_BREAK logs of a reference run with the same configuration). The runtime starts from exactly the machine the reference gave the
program: same vectors, ROM bytes and DOS state, so far allocations land on the same segments.
"""
import argparse
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import refmachine  # noqa: E402


def arr(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("mem")
    ap.add_argument("out")
    ap.add_argument("--psp", type=lambda v: int(v, 0), required=True)
    ap.add_argument("--first-mcb", type=lambda v: int(v, 0), required=True)
    ap.add_argument("--regs", required=True)
    ap.add_argument("--vga-log", required=True)
    ap.add_argument("--break-log", required=True)
    a = ap.parse_args()
    d = Path(a.mem).read_bytes()
    psp = d[a.psp << 4:(a.psp << 4) + 256]
    env_seg = struct.unpack_from("<H", psp, 0x2C)[0]
    mcbs, seg = [], a.first_mcb  # validate the chain the runtime will allocate from
    while True:
        hdr = d[seg << 4:(seg << 4) + 16]
        if hdr[0] not in (0x4D, 0x5A):
            raise SystemExit(f"bad MCB at {seg:04X}")
        mcbs.append((seg, hdr))
        if hdr[0] == 0x5A:
            break
        seg += struct.unpack_from("<H", hdr, 3)[0] + 1
    regs = {k: int(v, 16) for k, v in (p.split("=") for p in a.regs.split())}
    out = ["// Generated by recomp/recompiler/make_bootenv.py from a reference capture. Do not edit.",
           '#include "bootenv.h"', "namespace rc {"]
    regs_out = []
    for i, (lo, hi) in enumerate(refmachine.regions(a.psp)):
        out.append(arr(f"kRegion{i}", d[lo:hi]))
        regs_out.append(f"{{0x{lo:05X}, kRegion{i}, 0x{hi - lo:X}}}")
    out.append("const MemRegion kRegions[] = {" + ", ".join(regs_out) + "};")
    cbs = refmachine.callback_map(d)
    out.append("const CallbackVector kCallbacks[] = {" + ", ".join(f"{{{cb}, 0x{n:02X}}}" for cb, n in sorted(cbs.items())) + "};")
    entry = f"{regs['cs']:04X}:{regs['ip']:04X}"
    vga = refmachine.vga_timing(a.vga_log, refmachine.entry_ms(a.break_log, entry))
    out.append("const VgaTiming kVga[] = {" + ", ".join(
        "{" + ", ".join(f"{x:.12f}" if abs(x) < 1e17 else "-1e18" for x in r) + "}" for r in vga) + "};")
    out.append(f"const BootEnv kBootEnv = {{0x{a.psp:04X}, 0x{env_seg:04X}, 0x{a.first_mcb:04X}, kRegions, {len(regs_out)}, "
               f"kCallbacks, {len(cbs)},")
    out.append("    {" + ", ".join(f"0x{regs[r]:04X}" for r in
                         ("ax", "bx", "cx", "dx", "si", "di", "bp", "sp", "ds", "es", "ss", "cs", "ip", "flags")) + "},")
    rseg, roff, rstop = refmachine.realint_trampoline(d)
    iseg, ioff, icb = refmachine.idle_code(d)
    out.append(f"    kVga, {len(vga)}, {refmachine.pit0_phase(a.break_log, entry):.12f}, 0x{rseg:04X}, 0x{roff:04X}, {rstop},")
    out.append(f"    0x{iseg:04X}, 0x{ioff:04X}, {icb}}};")
    out.append("}  // namespace rc")
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"PSP {a.psp:04X} env {env_seg:04X} MCBs {[hex(s) for s, _ in mcbs]} callbacks {dict(sorted(cbs.items()))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
