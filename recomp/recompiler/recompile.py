#!/usr/bin/env python3
"""Statically recompile an unpacked DOS MZ program into C++ (one function per basic block).

    python3 recompile.py GAME.EXE OUTDIR --load-seg 0x0824 --ref-mem mem_entry.bin [--entries entries.txt]

Outputs OUTDIR/blocks.cpp (block functions + lookup table), OUTDIR/image.cpp and OUTDIR/ledger.json
(blocks, instructions, bytes covered, unsupported instructions). The reference machine's memory
(refmachine.regions) is loaded around the program so its BIOS/DOS stubs are translated too. Seeds: the
program entry, every MZ relocation that is a far CALL/JMP operand, every reference vector target, and
entries.txt lines `SSSS:OOOO` (added by discovery runs from the runtime's missing-target log).
"""
import argparse
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from discover import discover  # noqa: E402
from mzload import load_mz  # noqa: E402
from x86emit import MN, Unsupported, emit  # noqa: E402
import refmachine  # noqa: E402


def program_blocks(exe: str, load_seg: int, ref_mem: str, entries: str | None):
    """The program image with the reference regions in place, and every block discovered from the entry,
    the reference stubs, far-call relocations and the dynamic entries list."""
    img = load_mz(Path(exe).read_bytes(), load_seg)
    ref = Path(ref_mem).read_bytes()
    psp_seg = load_seg - 0x10
    refmachine.apply(img.memory, ref, load_seg, bytes(img.memory[load_seg << 4:(load_seg << 4) + img.image_size]))
    mem = img.memory
    seeds = {img.entry}
    seeds.update(refmachine.stub_entries(ref, psp_seg))
    for linear in img.relocs:
        if mem[linear - 3] in (0x9A, 0xEA):  # CALL FAR / JMP FAR ptr16:16 operand
            off = struct.unpack_from("<H", mem, linear - 2)[0]
            seg = struct.unpack_from("<H", mem, linear)[0]
            seeds.add((seg, off))
    if entries and Path(entries).exists():
        for line in Path(entries).read_text().split():
            seg, off = line.split(":")
            seeds.add((int(seg, 16), int(off, 16)))
    return img, discover(img, sorted(seeds))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("exe")
    ap.add_argument("outdir")
    ap.add_argument("--load-seg", type=lambda v: int(v, 0), default=0x0824)
    ap.add_argument("--entries", default=None)
    ap.add_argument("--ref-mem", required=True, help="reference memory capture at the program entry")
    args = ap.parse_args()

    img, blocks = program_blocks(args.exe, args.load_seg, args.ref_mem, args.entries)
    out = Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by recomp/recompiler/recompile.py. Do not edit.',
             '#include "cpu.h"', '#include "machine.h"', "namespace rc {", ""]
    table = []
    unsupported = {}
    covered = set()
    ninsn = 0
    for (cs, ip), b in sorted(blocks.items()):
        name = f"B_{cs:04X}_{ip:04X}"
        body = []
        ended = False
        for ins in b.insns:
            try:
                body += emit(ins, cs)
            except Unsupported as e:
                unsupported[str(e)] = unsupported.get(str(e), 0) + 1
                body.append(f'c.ip = 0x{ins.ip:04X}; rt_unsupported(c, "{e}"); return;')
                ended = True
                break
            ninsn += 1
            start = img.linear(cs, ins.ip)
            covered.update(range(start, start + ins.len))
        if b.kind == "callback":
            cb, nxt = b.callback
            body.append(f"c.icount++; c.ip = 0x{nxt:04X}; rt_callback(c, {cb}); return;")
            covered.update(range(img.linear(cs, (nxt - 4) & 0xFFFF), img.linear(cs, (nxt - 4) & 0xFFFF) + 4))
            ended = True
        if not ended and b.insns:
            last = b.insns[-1]
            if b.kind in ("fall", "invalid"):
                if b.kind == "invalid":
                    body.append(f'c.ip = 0x{(last.ip + last.len) & 0xFFFF:04X}; rt_unsupported(c, "invalid opcode"); return;')
                else:
                    body.append(f"c.ip = 0x{(last.ip + last.len) & 0xFFFF:04X}; return;")
        if not b.insns and b.kind != "callback":
            body.append(f'c.ip = 0x{ip:04X}; rt_unsupported(c, "invalid opcode"); return;')
        lines.append(f"static void {name}(Cpu& c) {{")
        lines += ["    " + l for l in body]
        lines.append("}")
        nbytes = sum(i.len for i in b.insns) + (4 if b.kind == "callback" else 0)
        table.append((cs, ip, name, sum(1 for l in body if "c.icount++;" in l and l.startswith("/*")), nbytes))
    lines.append("")
    lines.append("const BlockEntry g_blocks[] = {")
    lines += [f"    {{0x{cs:04X}, 0x{ip:04X}, {name}, {n}, {nb}}}," for cs, ip, name, n, nb in table]
    lines.append("};")
    lines.append(f"const unsigned g_block_count = {len(table)};")
    lines.append(f"const uint16_t g_load_seg = 0x{args.load_seg:04X};")
    lines.append("}  // namespace rc")
    (out / "blocks.cpp").write_text("\n".join(lines) + "\n")
    # The load module as DOS would place it at load_seg (relocations applied). Derived from the user's
    # own executable at build time: generated sources stay out of version control and distribution.
    image = bytes(img.memory[args.load_seg << 4:(args.load_seg << 4) + img.image_size])
    rows = [", ".join(f"0x{b:02X}" for b in image[i:i + 32]) for i in range(0, len(image), 32)]
    (out / "image.cpp").write_text("// Generated by recompile.py from the user's executable. Do not edit or distribute.\n"
                                   "#include <cstdint>\nnamespace rc {\n"
                                   f"extern const uint8_t g_image[{len(image)}] = {{\n" + ",\n".join(rows) + "\n};\n"
                                   f"extern const unsigned g_image_size = {len(image)};\n}}\n")
    ledger = {
        "exe": str(Path(args.exe).resolve()), "load_seg": args.load_seg,
        "blocks": len(table), "instructions": ninsn, "code_bytes_covered": len(covered),
        "image_bytes": img.image_size, "unsupported": unsupported,
    }
    (out / "ledger.json").write_text(json.dumps(ledger, indent=1))
    print(json.dumps(ledger, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
