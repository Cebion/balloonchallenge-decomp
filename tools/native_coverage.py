#!/usr/bin/env python3
"""Coverage of the native (decompiled/lifted) code units: which registered units were checked by
--verify-native in the recorded sessions (work/ls/va_NAME.verified, from work/ls/verify_all_native.sh).
Writes docs/native-coverage.md."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
units = {}
for f in sorted((ROOT / "src/game").glob("*.cpp")):
    for m in re.finditer(r'Native(?:Reg|Region) \w+\{([^}]*)\}', f.read_text()):
        name = re.search(r'"([^"]+)"', m.group(1)).group(1)
        units[name] = (f.name, "verified=*/false" not in m.group(1) and "false};" not in m.group(0))
checked, nested = {}, {}
for v in sorted((ROOT / "work/ls").glob("va_*.verified")):
    sess = v.stem[3:]
    text = v.read_text()
    direct, _, nested_part = text.partition("| nested:")
    for tok in direct.split()[1:]:
        n, c = tok.split("=")
        checked.setdefault(n, {})[sess] = int(c)
    for tok in nested_part.split():
        n, c = tok.split("=")
        nested.setdefault(n, {})[sess] = int(c)
lines = ["# Native code coverage", "",
         "Units registered in src/game and the recorded sessions in which `--verify-native` checked them (each",
         "entry compared with the recompiled code: registers, flags, instruction count, memory, video planes, port",
         "writes). A unit called from inside another native unit runs natively and is covered by the check of the",
         "outer unit (column 'nested'); runs from before the nested counter existed show no nested data.",
         "Generated by tools/native_coverage.py.", ""]
cov = [n for n in units if n in checked]
lines.append("%d of %d units checked at least once; %d checked entries in total." % (
    len(cov), len(units), sum(sum(d.values()) for d in checked.values())))
lines += ["", "| unit | file | checked entries (sessions) | nested runs |", "|---|---|---|---|"]
for n in sorted(units, key=lambda x: (x not in checked and x not in nested, x)):
    d, e = checked.get(n), nested.get(n)
    s1 = "%d (%s)" % (sum(d.values()), ", ".join(sorted(d))) if d else ("-" if e else "never reached")
    s2 = "%d" % sum(e.values()) if e else "-"
    lines.append("| %s | %s | %s | %s |" % (n, units[n][0], s1, s2))
(ROOT / "docs/native-coverage.md").write_text("\n".join(lines) + "\n")
print(next(l for l in lines if " units checked" in l))
