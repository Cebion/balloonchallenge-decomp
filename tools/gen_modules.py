#!/usr/bin/env python3
"""Generate native procedures for the separately compiled modules (segments 15D6-195B) with
recomp/recompiler/qblift.py: one function per far-call target, the whole segment as its range (RET/RETF
emitted exactly). Writes src/game/module_SSSS.cpp. Drafts: they count once --verify-native passes."""
import os
import sys
from pathlib import Path

KB = Path(__file__).resolve().parent.parent / "recomp/recompiler"
sys.path.insert(0, str(KB))
from recompile import program_blocks  # noqa: E402
from qblift import region_code  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SEGS = (0x15D6, 0x1664, 0x16CD, 0x1794, 0x17ED, 0x17FE, 0x1932, 0x1946, 0x195B)


def main() -> int:
    _, blocks = program_blocks(str(ROOT / "work/unpacked/BALLOONC.real.exe"), 0x0824, str(ROOT / "work/reference_entry.bin"),
                               str(ROOT / "recomp/entries.txt"))
    targets = {}
    for a, b in blocks.items():
        if b.kind == "call" and b.succ and b.succ[0][0] in SEGS and b.succ[0][0] != a[0]:
            targets.setdefault(b.succ[0][0], set()).add(b.succ[0][1])
    total = 0
    for seg in SEGS:
        ents = sorted(targets.get(seg, ()))
        if not ents:
            continue
        out = ["// Module segment %04X: generated by recomp/recompiler/qblift.py (tools/gen_modules.py): one" % seg,
               "// procedure per far-call target; qb.h helpers where a QuickBASIC pattern matches, the exact instruction",
               "// semantics elsewhere. Correctness: --verify-native.",
               '#include "common.h"', '#include "machine.h"', "", "namespace {", "", "using namespace bc;", ""]
        regs = []
        for e in ents:
            name = "mod_%04X_%04X" % (seg, e)
            code, _ = region_code(blocks, seg, 0, 0x10000, name, e)
            out += code + [""]
            regs.append('rc::NativeReg reg_%04X{0x%04X, 0x%04X, true, &%s, "%s"};' % (e, seg, e, name, name))
        out += regs + ["", "}  // namespace", ""]
        (ROOT / ("src/game/module_%04X.cpp" % seg)).write_text("\n".join(out))
        total += len(ents)
        print("%04X: %d procedures" % (seg, len(ents)))
    print("procedures", total)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
