#!/usr/bin/env python3
"""Generate native main-body regions for Balloon Challenge with recomp/recompiler/qblift.py:
address chunks of the main program, one function per entry (the chunk start, and every block entered from
outside the chunk). Writes src/game/region_XXXX.cpp. Drafts: they count once --verify-native passes.

    python3 tools/gen_regions.py 0700 CCC0 0800
"""
import os
import sys
from pathlib import Path

KB = Path(__file__).resolve().parent.parent / "recomp/recompiler"
sys.path.insert(0, str(KB))
from recompile import program_blocks  # noqa: E402
from qblift import region_code  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
CS = 0x0824


def main() -> int:
    lo0, hi0, size = (int(v, 16) for v in sys.argv[1:4])
    _, blocks = program_blocks(str(ROOT / "work/unpacked/BALLOONC.real.exe"), CS, str(ROOT / "work/reference_entry.bin"),
                               str(ROOT / "recomp/entries.txt"))
    body, work = set(), [(CS, 0x30)]
    while work:
        x = work.pop()
        if x in body or x not in blocks:
            continue
        body.add(x)
        b = blocks[x]
        work.extend(b.succ[1:] if b.kind == "call" else b.succ)
    preds = {}
    for a, b in blocks.items():
        for s in (b.succ[1:] if b.kind == "call" else b.succ):
            preds.setdefault(s, set()).add(a)
    total = 0
    for lo in range(lo0, hi0, size):
        hi = min(lo + size, hi0)
        inside = [x for x in body if x[0] == CS and lo <= x[1] < hi]
        if not inside:
            continue
        entries = sorted({x[1] for x in inside if x[1] == lo or any(not (p[0] == CS and lo <= p[1] < hi) for p in preds.get(x, ()))})
        if (CS, lo) not in body:  # the chunk start is not a block: entries only
            entries = [e for e in entries if e != lo]
        out = ["// Main program, region 0824:%04X-%04X: generated by recomp/recompiler/qblift.py (tools/gen_regions.py):" % (lo, hi),
               "// qb.h helpers where a QuickBASIC statement pattern matches, the exact instruction semantics elsewhere;",
               "// labels are block starts. One function per entry into the region. Correctness: --verify-native.",
               '#include "common.h"', '#include "machine.h"', "", "namespace {", "", "using namespace bc;", ""]
        regs = []
        for e in entries:
            code, _ = region_code(blocks, CS, lo, hi, "main_%04X" % e, e)
            out += code + [""]
            regs.append('rc::NativeRegion reg_%04X{0x0824, 0x%04X, 0x%04X, 0x%04X, &main_%04X, "main_%04X"};' % (e, e, lo, hi, e, e))
        out += regs + ["", "}  // namespace", ""]
        # A region entered at e covers [lo, hi): run_region_out uses [ip, end), so the start must be lo.
        (ROOT / ("src/game/region_%04X.cpp" % lo)).write_text("\n".join(out))
        total += len(entries)
        print("region %04X-%04X: %d entries" % (lo, hi, len(entries)))
    print("entries", total)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
